#pragma once

// Nonlinear 4-pole transistor-ladder low-pass, zero-delay feedback.
//
// Model (Huovilainen 2004, in TPT form after Zavalishin ch. 6): four
// one-pole stages with the differential-pair nonlinearity on input and
// output,
//
//     dy_i/dt = wc * ( tanh(x_i) - tanh(y_i) ),   x_1 = in - k*y_4,  x_i = y_(i-1)
//
// discretised with trapezoidal integrators (pre-warped g = tan(pi fc/fs)):
//
//     y_i = s_i + g * ( tanh(x_i) - tanh(y_i) ),   s_i <- 2 y_i - s_i
//
// Solvers (docs/dsp/filters-m3.md has the measurements behind the choice):
//
//   Newton      (production) Starts from the linearised solution and
//               applies Newton-Raphson on the full implicit system. The 4x4
//               Jacobian is bidiagonal plus one feedback entry: O(4) per
//               step. With backtracking (near Nyquist). Measured: 2
//               iterations match the converged solution to <= -78 dB, so the
//               production default is a fixed 2 (bounded CPU).
//   Linearised  tanh(v) -> v * T(v_est), T = tanh(v)/v, v_est from the
//               previous sample; the system is then linear and solved in
//               closed form ("cheap" ZDF method, Mystran / T. Voipio, KVR
//               2012). Kept as a measured reference: it deviates from the
//               exact solution by up to 24 dB in harmonic levels at high
//               resonance/drive and aliases 5-17 dB more.
//
// Small-signal both reduce to the linear ladder (verified in tests):
//     H_24 = (1 + c k) / ((1 + s)^4 + k),   H_12 = (1 + c k)(1 + s)^2 / ((1 + s)^4 + k)
// with bass compensation c in [0, 1]. k = 4 is the self-oscillation
// threshold. Above it the tanh terms set the amplitude and pull the pitch
// flat as a function of k. A measured correction table retunes the cutoff
// so self-oscillation tracks the requested frequency.
//
// Gain staging: input * drive * kInputScale into the model's voltage domain,
// divided back out at the output: drive changes saturation, not pass-band level.
// Output gain = (1 + c * min(k, 4)) / (kInputScale * max(drive, 1)):
//  * Bass compensation is applied at the OUTPUT. Applied at the input it
//    would drive the first tanh stage harder as resonance rises (measured in
//    M3b: +7 dB effective drive at k = 2.7, c = 0.5, costing 15-40 dB of
//    alias rejection). It restores level; it must not add drive. It stops
//    growing at the self-oscillation threshold k = 4.
//  * Drive above 0 dB is level-compensated (more saturation, same level).
//    Below 0 dB it is a plain input attenuator (cleaner and quieter).
//    Full compensation there would amplify the self-oscillation, whose
//    amplitude is set by the tanh stages and not by the input, to about
//    +12 dBFS per voice at -12 dB drive.

#include <algorithm>
#include <array>
#include <cmath>
#include <cstdint>
#include <limits>
#include <numbers>

namespace aurel::dsp
{

class LadderFilter
{
public:
    enum class Mode : std::uint8_t { LowPass24, LowPass12 };
    enum class Solver : std::uint8_t { Linearised, Newton };

    static constexpr double kInputScale = 0.5; // nominal +/-1 signal -> +/-0.5 in model units
    static constexpr double kMinCutoffHz = 5.0;
    static constexpr double kMaxCutoffRatio = 0.45;
    static constexpr double kMaxFeedback = 6.0;
    static constexpr double kNewtonTolerance = 1e-10;
    static constexpr int kDefaultIterations = 2;

    /** Self-oscillation pitch offset of the uncorrected model, in cents, at
        k = 4.0, 4.1, ... 6.0 (Newton, 2 iterations, 96 kHz, 1 kHz cutoff).
        Generated by Scripts/analysis/ladder_tuning_table.py. */
    static constexpr std::array<double, 21> kSelfOscillationOffsetCents {
        0.000, -10.284, -19.596, -28.054, -35.756, -42.786, -49.218,
        -55.115, -60.532, -65.518, -70.115, -74.359, -78.286, -81.922,
        -85.295, -88.429, -91.342, -94.056, -96.585, -98.945, -101.151
    };

    void prepare (double sampleRate) noexcept
    {
        fs = sampleRate;
        reset();
        setParameters (1000.0, 0.0, 1.0, 0.0);
    }

    void reset() noexcept
    {
        s.fill (0.0);
        yEst.fill (0.0);
        uEst = 0.0;
    }

    /** feedback k: 0 .. kMaxFeedback (4 = self-oscillation threshold).
        drive: linear input gain (> 0). bassCompensation: 0 .. 1. */
    void setParameters (double cutoffHz, double feedback, double drive, double bassCompensation) noexcept
    {
        k = std::clamp (feedback, 0.0, kMaxFeedback);
        double fc = cutoffHz;
        if (tuningCorrection && k > 4.0)
            fc *= std::exp2 (-selfOscillationOffsetCents (k) / 1200.0);
        fc = std::clamp (fc, kMinCutoffHz, kMaxCutoffRatio * fs);
        g = std::tan (std::numbers::pi * fc / fs);
        const double d = std::max (drive, 1e-3);
        inputGain = d * kInputScale;
        compensation = std::clamp (bassCompensation, 0.0, 1.0);
        outputGain = (1.0 + compensation * std::min (k, 4.0)) / (kInputScale * std::max (d, 1.0));
    }

    void setMode (Mode m) noexcept { mode = m; }
    void setSolver (Solver sv, int newtonIterations = kDefaultIterations) noexcept
    {
        solver = sv;
        maxIterations = std::max (1, newtonIterations);
    }

    /** Self-oscillation pitch correction (on by default). Off only for
        measuring the raw model. Takes effect at the next setParameters(). */
    void setTuningCorrection (bool on) noexcept { tuningCorrection = on; }

    [[nodiscard]] static double selfOscillationOffsetCents (double feedback) noexcept
    {
        const double pos = std::clamp ((feedback - 4.0) * 10.0, 0.0, 20.0);
        const auto i = std::min (static_cast<std::size_t> (pos), std::size_t { 19 });
        const double t = pos - static_cast<double> (i);
        return (1.0 - t) * kSelfOscillationOffsetCents[i] + t * kSelfOscillationOffsetCents[i + 1];
    }

    struct Taps
    {
        double lp24 = 0.0, lp12 = 0.0;
    };

    /** One sample; returns the output selected by setMode(). */
    double process (double input) noexcept
    {
        const auto t = processTaps (input);
        return mode == Mode::LowPass24 ? t.lp24 : t.lp12;
    }

    /** One sample; returns both outputs (for crossfading between them). */
    Taps processTaps (double input) noexcept
    {
        const double xin = input * inputGain;

        // --- Linearised closed-form solve (initial estimate) ---------------
        // Stage i's input estimate equals stage i-1's output estimate, so only
        // five T() values are distinct.
        const std::array<double, 5> T { tanhOverX (uEst), tanhOverX (yEst[0]), tanhOverX (yEst[1]),
                                        tanhOverX (yEst[2]), tanhOverX (yEst[3]) };
        std::array<double, 4> a {}, b {};
        for (std::size_t i = 0; i < 4; ++i)
        {
            const double inv = 1.0 / (1.0 + g * T[i + 1]);
            a[i] = g * T[i] * inv;
            b[i] = s[i] * inv;
        }
        const double A = a[0] * a[1] * a[2] * a[3];
        const double B = a[3] * (a[2] * (a[1] * b[0] + b[1]) + b[2]) + b[3];

        std::array<double, 4> y {};
        y[3] = (A * xin + B) / (1.0 + k * A);
        const double u0 = xin - k * y[3];
        y[0] = a[0] * u0 + b[0];
        y[1] = a[1] * y[0] + b[1];
        y[2] = a[2] * y[1] + b[2];
        y[3] = a[3] * y[2] + b[3];

        lastIterations = 0;
        if (solver == Solver::Newton)
            refineNewton (xin, y);

        for (std::size_t i = 0; i < 4; ++i)
        {
            s[i] = 2.0 * y[i] - s[i];
            yEst[i] = y[i];
        }
        uEst = xin - k * y[3];

        return { y[3] * outputGain, y[1] * outputGain };
    }

    [[nodiscard]] int getLastIterations() const noexcept { return lastIterations; }
    [[nodiscard]] double getG() const noexcept { return g; }
    /** Samples where Newton ended above tolerance (only meaningful with an
        iteration limit large enough to converge, e.g. in tests). */
    [[nodiscard]] long long getNonConvergedCount() const noexcept { return nonConverged; }

private:
    static double tanhOverX (double v) noexcept
    {
        return std::abs (v) < 1e-4 ? 1.0 - v * v / 3.0 : std::tanh (v) / v;
    }

    /** Newton with backtracking: a full step is taken; if the residual did
        not decrease, the step is halved (near Nyquist, g >> 1, full steps can
        overshoot). The residual check reuses the evaluation that starts each
        iteration, so it costs nothing when the full step works. Tanh values
        are shared between stage outputs and the next stage's input: five
        tanh per iteration. A non-finite result falls back to the linearised
        estimate. */
    void refineNewton (double xin, std::array<double, 4>& y) noexcept
    {
        const std::array<double, 4> fallback = y;
        std::array<double, 4> yPrev = y, stepPrev {};
        double prevResidual = std::numeric_limits<double>::infinity();
        double t = 1.0;

        for (int it = 0; it < maxIterations; ++it)
        {
            const double tu = std::tanh (xin - k * y[3]);
            const std::array<double, 4> ty { std::tanh (y[0]), std::tanh (y[1]), std::tanh (y[2]), std::tanh (y[3]) };
            const std::array<double, 4> tx { tu, ty[0], ty[1], ty[2] };

            std::array<double, 4> F {};
            double residual = 0.0;
            for (std::size_t i = 0; i < 4; ++i)
            {
                F[i] = y[i] - s[i] - g * (tx[i] - ty[i]);
                residual = std::max (residual, std::abs (F[i]));
            }
            lastIterations = it + 1;

            if (residual >= prevResidual && t > 1.0 / 64.0)
            {
                t *= 0.5; // backtrack along the previous direction
                for (std::size_t i = 0; i < 4; ++i)
                    y[i] = yPrev[i] + t * stepPrev[i];
                continue;
            }
            if (residual < kNewtonTolerance)
                return;

            // J * delta = -F, with J bidiagonal plus the feedback entry dF1/dy4.
            // Each delta_i = alpha_i + beta_i * delta_4.
            std::array<double, 4> alpha {}, beta {};
            {
                const double d0 = 1.0 + g * (1.0 - ty[0] * ty[0]);
                const double e = g * k * (1.0 - tu * tu);
                alpha[0] = -F[0] / d0;
                beta[0] = -e / d0;
            }
            for (std::size_t i = 1; i < 4; ++i)
            {
                const double inv = 1.0 / (1.0 + g * (1.0 - ty[i] * ty[i]));
                const double c = g * (1.0 - tx[i] * tx[i]);
                alpha[i] = (-F[i] + c * alpha[i - 1]) * inv;
                beta[i] = c * beta[i - 1] * inv;
            }
            const double d4 = alpha[3] / (1.0 - beta[3]);

            prevResidual = residual;
            yPrev = y;
            t = 1.0;
            for (std::size_t i = 0; i < 4; ++i)
            {
                stepPrev[i] = alpha[i] + beta[i] * d4;
                y[i] += stepPrev[i];
            }
        }

        ++nonConverged;
        if (! (std::isfinite (y[0]) && std::isfinite (y[1]) && std::isfinite (y[2]) && std::isfinite (y[3])))
            y = fallback;
    }

    double fs = 48000.0;
    double g = 0.0, k = 0.0, inputGain = kInputScale, compensation = 0.0, outputGain = 1.0 / kInputScale;
    std::array<double, 4> s {}, yEst {};
    double uEst = 0.0;
    Mode mode = Mode::LowPass24;
    Solver solver = Solver::Newton;
    int maxIterations = kDefaultIterations;
    int lastIterations = 0;
    long long nonConverged = 0;
    bool tuningCorrection = true;
};

} // namespace aurel::dsp
